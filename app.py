# API ค้นหา
# ============================================================

@app.route("/api/search")
def search_place():

    query = request.args.get("q", "").strip().lower()

    if not query:
        return jsonify([])

    results = []

    for place in PLACES:

        number_match = query in place["number"].lower()

        name_match = query in place["name"].lower()

        keyword_match = any(
            query in keyword.lower()
            for keyword in place["keywords"]
        )

        if number_match or name_match or keyword_match:

            results.append({
                "number": place["number"],
                "name": place["name"],
                "x": place["x"],
                "y": place["y"]
            })

    return jsonify(results)


